CREATE OR REPLACE VIEW LIBRA.REPORTING.TRANSACTION_DRILLTHROUGH AS
SELECT I.INVOICE_ID,I.SHIPMENT_ID,I.INVOICE_DATE_KEY,C.COUNTRY_CODE,
       CU.CUSTOMER_ID,CC.COST_CENTER_ID,CY.CURRENCY_CODE,I.ORIGINAL_AMOUNT,
       I.FX_RATE_TO_EUR,I.AMOUNT_EUR,I.SOURCE_BATCH_ID,I.SOURCE_FILE,I.SOURCE_ROW_NUMBER
FROM LIBRA.CORE.FACT_INVOICE I
JOIN LIBRA.CORE.DIM_COUNTRY C ON C.COUNTRY_KEY=I.COUNTRY_KEY
JOIN LIBRA.CORE.DIM_CUSTOMER CU ON CU.CUSTOMER_KEY=I.CUSTOMER_KEY
JOIN LIBRA.CORE.DIM_COST_CENTER CC ON CC.COST_CENTER_KEY=I.COST_CENTER_KEY
JOIN LIBRA.CORE.DIM_CURRENCY CY ON CY.CURRENCY_KEY=I.CURRENCY_KEY;
