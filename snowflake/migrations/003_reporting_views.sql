CREATE OR REPLACE VIEW LIBRA.REPORTING.MONTHLY_COUNTRY_FINANCE AS
WITH REVENUE AS (
  SELECT D.MONTH_START,I.COUNTRY_KEY,SUM(I.AMOUNT_EUR)::NUMBER(20,2) REVENUE_EUR
  FROM LIBRA.CORE.FACT_INVOICE I JOIN LIBRA.CORE.DIM_DATE D ON D.DATE_KEY=I.INVOICE_DATE_KEY
  GROUP BY D.MONTH_START,I.COUNTRY_KEY
), COST AS (
  SELECT D.MONTH_START,O.COUNTRY_KEY,SUM(O.AMOUNT_EUR)::NUMBER(20,2) COST_EUR
  FROM LIBRA.CORE.FACT_OPERATIONAL_COST O
  JOIN LIBRA.CORE.DIM_DATE D ON D.DATE_KEY=O.POSTING_DATE_KEY
  GROUP BY D.MONTH_START,O.COUNTRY_KEY
), KEYS AS (
  SELECT MONTH_START,COUNTRY_KEY FROM REVENUE UNION
  SELECT MONTH_START,COUNTRY_KEY FROM COST
)
SELECT K.MONTH_START,C.COUNTRY_CODE,COALESCE(R.REVENUE_EUR,0)::NUMBER(20,2) TOTAL_REVENUE_EUR,
       COALESCE(O.COST_EUR,0)::NUMBER(20,2) TOTAL_OPERATIONAL_COST_EUR,
       (COALESCE(R.REVENUE_EUR,0)-COALESCE(O.COST_EUR,0))::NUMBER(20,2) GROSS_PROFIT_EUR
FROM KEYS K JOIN LIBRA.CORE.DIM_COUNTRY C USING(COUNTRY_KEY)
LEFT JOIN REVENUE R USING(MONTH_START,COUNTRY_KEY)
LEFT JOIN COST O USING(MONTH_START,COUNTRY_KEY);
-- statement
CREATE OR REPLACE VIEW LIBRA.REPORTING.ROUTE_PROFITABILITY AS
WITH REVENUE AS (
  SELECT D.MONTH_START,I.ROUTE_KEY,SUM(I.AMOUNT_EUR)::NUMBER(20,2) REVENUE_EUR
  FROM LIBRA.CORE.FACT_INVOICE I JOIN LIBRA.CORE.DIM_DATE D ON D.DATE_KEY=I.INVOICE_DATE_KEY
  GROUP BY D.MONTH_START,I.ROUTE_KEY
), COST AS (
  SELECT D.MONTH_START,O.ROUTE_KEY,SUM(O.AMOUNT_EUR)::NUMBER(20,2) COST_EUR
  FROM LIBRA.CORE.FACT_OPERATIONAL_COST O
  JOIN LIBRA.CORE.DIM_DATE D ON D.DATE_KEY=O.POSTING_DATE_KEY
  GROUP BY D.MONTH_START,O.ROUTE_KEY
), SHIPMENTS AS (
  SELECT D.MONTH_START,S.ROUTE_KEY,COUNT(DISTINCT S.SHIPMENT_ID) SHIPMENT_COUNT
  FROM LIBRA.CORE.FACT_SHIPMENT S JOIN LIBRA.CORE.DIM_DATE D ON D.DATE_KEY=S.SHIPMENT_DATE_KEY
  GROUP BY D.MONTH_START,S.ROUTE_KEY
), KEYS AS (
  SELECT MONTH_START,ROUTE_KEY FROM REVENUE UNION
  SELECT MONTH_START,ROUTE_KEY FROM COST UNION
  SELECT MONTH_START,ROUTE_KEY FROM SHIPMENTS
)
SELECT K.MONTH_START,R.ROUTE_ID,COALESCE(S.SHIPMENT_COUNT,0) SHIPMENT_COUNT,
  COALESCE(I.REVENUE_EUR,0)::NUMBER(20,2) TOTAL_REVENUE_EUR,
  COALESCE(O.COST_EUR,0)::NUMBER(20,2) OPERATIONAL_COST_EUR,
  (COALESCE(I.REVENUE_EUR,0)-COALESCE(O.COST_EUR,0))::NUMBER(20,2) GROSS_PROFIT_EUR
FROM KEYS K JOIN LIBRA.CORE.DIM_ROUTE R USING(ROUTE_KEY)
LEFT JOIN REVENUE I USING(MONTH_START,ROUTE_KEY)
LEFT JOIN COST O USING(MONTH_START,ROUTE_KEY)
LEFT JOIN SHIPMENTS S USING(MONTH_START,ROUTE_KEY);
