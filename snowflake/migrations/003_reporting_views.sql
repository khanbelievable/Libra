CREATE OR REPLACE VIEW LIBRA.REPORTING.BUDGET_VS_ACTUAL AS
SELECT B.MONTH_DATE_KEY, B.COST_CENTER_KEY, B.AMOUNT_EUR BUDGET_AMOUNT_EUR,
       COALESCE(SUM(O.AMOUNT_EUR),0)::NUMBER(20,2) ACTUAL_COST_EUR,
       (B.AMOUNT_EUR-COALESCE(SUM(O.AMOUNT_EUR),0))::NUMBER(20,2) VARIANCE_EUR
FROM LIBRA.CORE.FACT_BUDGET B
LEFT JOIN LIBRA.CORE.FACT_OPERATIONAL_COST O
  ON O.COST_CENTER_KEY=B.COST_CENTER_KEY
 AND TO_NUMBER(TO_CHAR(TO_DATE(O.POSTING_DATE_KEY::VARCHAR,'YYYYMMDD'),'YYYYMM01'))=B.MONTH_DATE_KEY
GROUP BY B.MONTH_DATE_KEY,B.COST_CENTER_KEY,B.AMOUNT_EUR;
